def inventory_level_to_count_level(level: str) -> str:
    """Map inventory-level labels to physical count buckets.

    R0E and R0N both belong to the physical R0 bucket. R0N is generated
    continuation life and should not be treated as independent stock.
    """
    level = str(level).upper().strip()
    if level in ["R0", "R0E", "R0N"]:
        return "R0"
    return level


def default_capacity_hits(level: str) -> int:
    level = str(level).upper().strip()
    if level == "R0":
        level = "R0E"
    return int(DEFAULT_CAP_UNITS.get(level, 1) * UNIT_HITS)


def inventory_row_for_count_level(inventory_df: pd.DataFrame, count_level: str) -> pd.Series:
    """Return the stock row used for inventory availability by count level."""
    count_level = str(count_level).upper().strip()
    if count_level == "R0":
        sub = inventory_df[inventory_df["regrind_level"] == "R0E"]
    else:
        sub = inventory_df[inventory_df["regrind_level"] == count_level]
    if len(sub) == 0:
        return pd.Series({"available_count": 0, "min_reserve_count": 0})
    return sub.iloc[0]


def build_capacity_units(inventory_df: pd.DataFrame) -> Dict[str, int]:
    """Build CAP_UNITS from CSV capacity_hits.

    capacity_hits must be divisible by UNIT_HITS. R0N may be inventory_mode=generated;
    its capacity still controls continuation capacity generated by R0E usage.
    """
    cap: Dict[str, int] = DEFAULT_CAP_UNITS.copy()
    for _, row in inventory_df.iterrows():
        level = str(row["regrind_level"]).upper().strip()
        if level not in REGRIND_LEVELS:
            continue
        hits = int(row.get("capacity_hits", default_capacity_hits(level)))
        if hits <= 0:
            hits = default_capacity_hits(level)
        if hits % UNIT_HITS != 0:
            raise ValueError(
                f"capacity_hits for {level} must be divisible by UNIT_HITS={UNIT_HITS}. Got {hits}."
            )
        cap[level] = hits // UNIT_HITS
    for level in REGRIND_LEVELS:
        cap.setdefault(level, DEFAULT_CAP_UNITS[level])
    return cap


