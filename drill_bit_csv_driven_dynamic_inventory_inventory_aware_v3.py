def prepare_pn_table_from_df(plan_df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, item in plan_df.iterrows():
        pn = str(item["pn"])
        batch_id = str(item.get("batch_id", pn))
        job_id = str(item.get("job_id", f"{pn}|{batch_id}"))
        panels = int(item["panels"])
        A = int(item["A_per_panel"]) * panels
        B = int(item["B_per_panel"]) * panels
        C = int(item["C_per_panel"]) * panels
        total = A + B + C

        rows.append({
            "job_id": job_id,
            "pn": pn,
            "batch_id": batch_id,
            "panels": panels,
            "due_priority": int(item.get("due_priority", 0)),
            "fixed_sequence": item.get("fixed_sequence", np.nan),
            "remark": item.get("remark", ""),

            "A_holes": A,
            "B_holes": B,
            "C_holes": C,
            "A_units": to_units(A) if A > 0 else 0,
            "B_units": to_units(B) if B > 0 else 0,
            "C_units": to_units(C) if C > 0 else 0,
            "A_ratio": A / max(total, 1),
            "B_ratio": B / max(total, 1),
            "C_ratio": C / max(total, 1),
        })
    return pd.DataFrame(rows)


def build_base_cost_weights(inventory_df: pd.DataFrame) -> Dict[str, float]:
    """Build physical-count cost weights from inventory rows.

    R0 cost is taken from R0E because R0N is generated continuation life and
    should not define independent R0 stock/cost.
    """
    weights: Dict[str, float] = {}
    for _, row in inventory_df.iterrows():
        level = str(row["regrind_level"]).upper()
        if level == "R0N":
            continue
        count_level = inventory_level_to_count_level(level)
        if count_level not in COUNT_LEVELS:
            continue
        base = row.get("base_cost_weight", np.nan)
        if pd.isna(base):
            base = FALLBACK_BASE_COST_WEIGHTS[count_level]
        weights[count_level] = float(base)
    for r in COUNT_LEVELS:
        weights.setdefault(r, FALLBACK_BASE_COST_WEIGHTS[r])
    return weights

def build_dynamic_cost_weights(inventory_df: pd.DataFrame, policy: pd.Series) -> Tuple[Dict[str, float], pd.DataFrame]:
    """Build dynamic cost by physical count level and report row-level details.

    R0 dynamic cost is based on R0E. R0N is generated continuation capacity, so
    it is included in the report but does not overwrite the R0 cost.
    """
    w_inventory = as_float(policy, "w_inventory", 1.0)
    policy_prefer = policy.get("preferred_regrind", None)
    policy_strength = as_float(policy, "preference_strength", 0.0)

    rows = []
    weights: Dict[str, float] = {}

    for _, row in inventory_df.iterrows():
        level = str(row["regrind_level"]).upper()
        count_level = inventory_level_to_count_level(level)
        base = row.get("base_cost_weight", np.nan)
        if pd.isna(base):
            base = 0.0 if level == "R0N" else FALLBACK_BASE_COST_WEIGHTS[count_level]
        base = float(base)

        priority_consume = int(row.get("priority_consume", 0))
        shortage_risk = int(row.get("shortage_risk", 0))
        available = int(row.get("available_count", 0))
        reserve = int(row.get("min_reserve_count", 0))
        inventory_mode = str(row.get("inventory_mode", "stock")).lower().strip()
        capacity_hits = int(row.get("capacity_hits", default_capacity_hits(level)))

        consume_discount = w_inventory * 0.45 * priority_consume
        shortage_penalty = w_inventory * 0.75 * shortage_risk
        reserve_penalty = w_inventory * 0.75 if inventory_mode != "generated" and available <= reserve else 0.0
        policy_discount = policy_strength if policy_prefer in [level, count_level] else 0.0

        dynamic = max(MIN_DYNAMIC_COST, base - consume_discount - policy_discount + shortage_penalty + reserve_penalty)

        # Do not let R0N overwrite R0; R0 cost is defined by R0E physical stock.
        if level != "R0N" and count_level in COUNT_LEVELS:
            weights[count_level] = dynamic

        rows.append({
            "regrind_level": level,
            "count_level": count_level,
            "inventory_mode": inventory_mode,
            "capacity_hits": capacity_hits,
            "base_cost_weight": base,
            "available_count": available,
            "min_reserve_count": reserve,
            "priority_consume": priority_consume,
            "shortage_risk": shortage_risk,
            "consume_discount": consume_discount,
            "policy_discount": policy_discount,
            "shortage_penalty": shortage_penalty,
            "reserve_penalty": reserve_penalty,
            "dynamic_cost_weight": dynamic,
        })

    for r in COUNT_LEVELS:
        weights.setdefault(r, FALLBACK_BASE_COST_WEIGHTS[r])
    return weights, pd.DataFrame(rows)

def build_inventory_allowed_counts(inventory_df: pd.DataFrame) -> Dict[str, int]:
    """Allowed physical bit counts after reserving safety stock.

    R0 availability comes from R0E stock. R0N is generated continuation capacity
    and is not treated as independent inventory.
    """
    allowed: Dict[str, int] = {r: 0 for r in COUNT_LEVELS}
    for _, row in inventory_df.iterrows():
        level = str(row["regrind_level"]).upper()
        if level == "R0N":
            continue
        count_level = inventory_level_to_count_level(level)
        if count_level not in COUNT_LEVELS:
            continue
        inventory_mode = str(row.get("inventory_mode", "stock")).lower().strip()
        if inventory_mode == "generated":
            continue
        available = int(row.get("available_count", 0))
        reserve = int(row.get("min_reserve_count", 0))
        allowed[count_level] = max(0, available - reserve)
    return allowed

def incremental_inventory_overuse(
    counts: Dict[str, int],
    used_counts_before: Optional[Dict[str, int]],
    inventory_allowed_counts: Optional[Dict[str, int]],
) -> Tuple[int, Dict[str, int]]:
    """Compute incremental overuse caused by this candidate allocation.

    The incremental form avoids double-counting overuse across production steps.
    For each level:
        before_over = max(0, used_before - allowed)
        after_over  = max(0, used_before + candidate_count - allowed)
        incremental = after_over - before_over
    """
    per_level: Dict[str, int] = {r: 0 for r in COUNT_LEVELS}
    if used_counts_before is None or inventory_allowed_counts is None:
        return 0, per_level

    total = 0
    for r in COUNT_LEVELS:
        before = int(used_counts_before.get(r, 0))
        add = int(counts.get(r, 0))
        allowed = int(inventory_allowed_counts.get(r, 0))
        before_over = max(0, before - allowed)
        after_over = max(0, before + add - allowed)
        inc = max(0, after_over - before_over)
        per_level[r] = int(inc)
        total += int(inc)
    return int(total), per_level


