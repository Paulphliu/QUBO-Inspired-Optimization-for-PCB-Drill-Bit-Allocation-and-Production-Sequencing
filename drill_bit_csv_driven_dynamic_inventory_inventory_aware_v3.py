def ceil_div(a: int, b: int) -> int:
    return (a + b - 1) // b


def to_units(hits: int) -> int:
    if hits % UNIT_HITS != 0:
        raise ValueError(
            f"Hits {hits} is not divisible by UNIT_HITS={UNIT_HITS}. "
            f"Please make sure hole counts are multiples of {UNIT_HITS}."
        )
    return hits // UNIT_HITS


def clean_str_value(v) -> Optional[str]:
    if pd.isna(v):
        return None
    s = str(v).strip()
    if s == "" or s.lower() in ["nan", "none", "null"]:
        return None
    return s


def as_float(row: pd.Series, col: str, default: float) -> float:
    if col not in row or pd.isna(row[col]):
        return float(default)
    return float(row[col])


def resolve_default_path(filename: str) -> Path:
    return DEFAULT_TEMPLATE_DIR / filename


def read_csv_with_validation(path: Path, required_cols: List[str], name: str) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Cannot find {name} CSV: {path}")
    df = pd.read_csv(path)
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"{name} CSV is missing columns: {missing}. File: {path}")
    return df


