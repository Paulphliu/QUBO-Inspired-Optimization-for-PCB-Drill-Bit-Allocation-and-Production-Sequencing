def parse_sequence_string(sequence: str) -> List[str]:
    if not isinstance(sequence, str) or not sequence.strip():
        return []
    return [x.strip() for x in sequence.split("->") if x.strip()]


def common_due_penalty_from_sequence(sequence: str, pn_df: pd.DataFrame) -> float:
    priority_map = {str(row["job_id"]): int(row.get("due_priority", 0)) for _, row in pn_df.iterrows()}
    due = 0.0
    for step, job_id in enumerate(parse_sequence_string(sequence), start=1):
        due += priority_map.get(job_id, 0) * max(0, step - 1) * DUE_STEP_PENALTY_SCALE
    return float(due)


def inventory_overuse_from_counts(row: pd.Series, inventory_df: pd.DataFrame) -> Tuple[int, Dict[str, int]]:
    allowed_counts = build_inventory_allowed_counts(inventory_df)
    per_level: Dict[str, int] = {}
    total = 0
    for r in COUNT_LEVELS:
        used = int(row.get(f"{r}_count", 0))
        allowed = int(allowed_counts.get(r, 0))
        over = max(0, used - allowed)
        per_level[r] = int(over)
        total += int(over)
    return int(total), per_level

def add_common_evaluation_columns(summary_df, pn_df, inventory_df, base_cost_weights, dynamic_cost_weights):
    rows = []
    for _, row in summary_df.iterrows():
        out = row.to_dict()
        r_counts = {r: int(row.get(f"{r}_count", 0)) for r in COUNT_LEVELS}
        eval_base_cost = sum(base_cost_weights[r] * r_counts[r] for r in COUNT_LEVELS)
        eval_dynamic_cost = sum(dynamic_cost_weights[r] * r_counts[r] for r in COUNT_LEVELS)
        eval_due = common_due_penalty_from_sequence(str(row.get("sequence", "")), pn_df)
        over_total, over_by_level = inventory_overuse_from_counts(row, inventory_df)
        over_penalty = EVAL_W_INVENTORY_OVERUSE * over_total
        eval_base_score = EVAL_W_CHANGE * float(row.get("tool_change_count", 0)) + EVAL_W_COST * eval_base_cost
        eval_dynamic_score = EVAL_W_CHANGE * float(row.get("tool_change_count", 0)) + EVAL_W_COST * eval_dynamic_cost
        eval_practical_score = eval_dynamic_score + EVAL_W_DUE * eval_due + over_penalty
        out.update({
            "optimization_objective": float(row.get("objective_score", 0.0)),
            "eval_base_cost_score": float(eval_base_cost),
            "eval_dynamic_cost_score": float(eval_dynamic_cost),
            "eval_base_score": float(eval_base_score),
            "eval_dynamic_score": float(eval_dynamic_score),
            "eval_common_due_penalty": float(eval_due),
            "eval_inventory_overuse_count": int(over_total),
            "eval_inventory_overuse_penalty": float(over_penalty),
            "eval_inventory_overuse_R0": over_by_level["R0"],
            "eval_inventory_overuse_R1": over_by_level["R1"],
            "eval_inventory_overuse_R2": over_by_level["R2"],
            "eval_inventory_overuse_R3": over_by_level["R3"],
            "eval_practical_score": float(eval_practical_score),
        })
        rows.append(out)
    return pd.DataFrame(rows)


def build_common_evaluation_summary(best_df: pd.DataFrame) -> pd.DataFrame:
    cols = [
        "policy_name", "baseline_mode", "order_name", "sequence",
        "tool_change_count", "R0_count", "R1_count", "R2_count", "R3_count",
        "optimization_objective", "optimization_inventory_overuse_count", "optimization_inventory_overuse_penalty", "eval_base_score", "eval_dynamic_score",
        "eval_common_due_penalty", "eval_inventory_overuse_count",
        "eval_inventory_overuse_penalty", "eval_practical_score",
    ]
    keep = [c for c in cols if c in best_df.columns]
    return best_df[keep].sort_values("eval_practical_score").reset_index(drop=True)


