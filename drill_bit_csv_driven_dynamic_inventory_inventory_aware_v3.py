def allocate_r0e_fixed(row: pd.Series, rules: Dict[str, List[str]]) -> Dict[str, int]:
    """Allocate each hole type that only allows R0E to R0E.

    This keeps Type A behavior compatible with the old model when A only allows R0E.
    """
    alloc: Dict[str, int] = {}
    for h in HOLE_TYPES:
        if rules[h] == ["R0E"]:
            alloc[f"{h}_R0E"] = int(row[f"{h}_units"])
    return alloc


def fill_remaining_by_single_choice(row: pd.Series, alloc: Dict[str, int], rules: Dict[str, List[str]], choice_func) -> Dict[str, int]:
    out = dict(alloc)
    r0n_capacity = count_physical_bits(normalize_alloc(out))["R0"] * CAP_UNITS["R0N"]
    r0n_used = sum(out.get(f"{h}_R0N", 0) for h in HOLE_TYPES)

    for h in HOLE_TYPES:
        demand = int(row[f"{h}_units"])
        already = sum(out.get(f"{h}_{r}", 0) for r in REGRIND_LEVELS)
        rem = max(0, demand - already)
        if rem == 0:
            continue

        # Use R0N first if allowed, because it consumes continuation capacity.
        if "R0N" in rules[h]:
            use0 = min(rem, max(0, r0n_capacity - r0n_used))
            if use0 > 0:
                out[f"{h}_R0N"] = out.get(f"{h}_R0N", 0) + use0
                rem -= use0
                r0n_used += use0

        if rem > 0:
            choices = [r for r in rules[h] if r != "R0N"]
            if not choices:
                # infeasible by rules; leave unmet so evaluator penalizes it.
                continue
            r = choice_func(choices)
            out[f"{h}_{r}"] = out.get(f"{h}_{r}", 0) + rem
    return out


def allocation_efficiency_first(row: pd.Series, rules: Dict[str, List[str]]) -> Dict[str, int]:
    """Use R0N first, then the allowed level with largest capacity."""
    base = allocate_r0e_fixed(row, rules)

    def largest_capacity(choices: List[str]) -> str:
        return max(choices, key=lambda r: (capacity_for(r), -cost_for(r, FALLBACK_BASE_COST_WEIGHTS)))

    return fill_remaining_by_single_choice(row, base, rules, largest_capacity)


def allocation_static_cost_first(row: pd.Series, rules: Dict[str, List[str]], base_cost_weights: Dict[str, float]) -> Dict[str, int]:
    """Use R0N first, then the allowed level with the lowest base cost."""
    base = allocate_r0e_fixed(row, rules)

    def cheapest_base(choices: List[str]) -> str:
        return min(choices, key=lambda r: cost_for(r, base_cost_weights))

    return fill_remaining_by_single_choice(row, base, rules, cheapest_base)


def allocation_dynamic_preference_greedy(row: pd.Series, rules: Dict[str, List[str]], cost_weights: Dict[str, float]) -> Dict[str, int]:
    """Use R0N first, then the allowed level with the lowest dynamic cost."""
    base = allocate_r0e_fixed(row, rules)

    def cheapest_dynamic(choices: List[str]) -> str:
        return min(choices, key=lambda r: cost_for(r, cost_weights))

    return fill_remaining_by_single_choice(row, base, rules, cheapest_dynamic)


def split_candidates(rem: int, choices: List[str]) -> List[Dict[str, int]]:
    """Generate candidate splits for remaining units across allowed regrinds.

    Kept intentionally compact to avoid exploding exhaustive sequence search.
    """
    choices = list(dict.fromkeys(choices))
    if rem <= 0:
        return [{}]
    if not choices:
        return [{}]
    if len(choices) == 1:
        return [{choices[0]: rem}]

    candidates: List[Dict[str, int]] = []

    # all-in-one choices
    for r in choices:
        candidates.append({r: rem})

    # pair splits to give balanced_dynamic real alternatives
    fractions = [0.25, 0.5, 0.75]
    for i, r1 in enumerate(choices):
        for r2 in choices[i + 1:]:
            for f in fractions:
                u1 = int(round(rem * f))
                u2 = rem - u1
                candidates.append({r1: u1, r2: u2})

    # one equal split among all choices
    base = rem // len(choices)
    d = {r: base for r in choices}
    d[choices[-1]] += rem - sum(d.values())
    candidates.append(d)

    # de-duplicate
    seen = set()
    out = []
    for c in candidates:
        c = {r: int(v) for r, v in c.items() if int(v) > 0}
        key = tuple(sorted(c.items()))
        if key not in seen:
            seen.add(key)
            out.append(c)
    return out


def allocation_balanced_dynamic(
    row: pd.Series,
    rules: Dict[str, List[str]],
    cost_weights: Dict[str, float],
    active_policy: pd.Series,
    policy_name: str,
    used_counts_before: Optional[Dict[str, int]] = None,
    inventory_allowed_counts: Optional[Dict[str, int]] = None,
    w_inventory_overuse_optimization: float = 0.0,
) -> Dict[str, int]:
    """QUBO-inspired candidate search using the hole-rule CSV.

    It searches feasible-like splits under the allowed hole/regrind rules and
    chooses the allocation with the lowest internal objective.
    """
    best_score = float("inf")
    best_alloc: Optional[Dict[str, int]] = None

    # Start from hole types that are forced to R0E only.
    forced = allocate_r0e_fixed(row, rules)

    # Hole types still to optimize.
    variable_holes = [h for h in HOLE_TYPES if not (rules[h] == ["R0E"])]

    # Generate R0E candidate use for variable holes if allowed.
    r0e_options: Dict[str, List[int]] = {}
    for h in variable_holes:
        units = int(row[f"{h}_units"])
        if "R0E" in rules[h]:
            r0e_options[h] = sorted(set([0, units // 4, units // 2, units]))
        else:
            r0e_options[h] = [0]

    # Product over R0E choices for variable hole types.
    r0e_keys = variable_holes
    r0e_products = itertools.product(*(r0e_options[h] for h in r0e_keys)) if r0e_keys else [()]

    step_policy = get_step_policy(1, active_policy, cost_weights)

    for r0e_vals in r0e_products:
        base_alloc = dict(forced)
        for h, val in zip(r0e_keys, r0e_vals):
            if val > 0:
                base_alloc[f"{h}_R0E"] = val

        r0_count = count_physical_bits(normalize_alloc(base_alloc))["R0"]
        r0n_cap = r0_count * CAP_UNITS["R0N"]

        # R0N allocation candidates per variable hole type, sequentially.
        def recurse_r0n(idx: int, alloc_so_far: Dict[str, int], cap_left: int):
            if idx >= len(variable_holes):
                yield alloc_so_far
                return
            h = variable_holes[idx]
            demand = int(row[f"{h}_units"])
            assigned = sum(alloc_so_far.get(f"{h}_{r}", 0) for r in REGRIND_LEVELS)
            rem = max(0, demand - assigned)
            if rem <= 0 or "R0N" not in rules[h]:
                yield from recurse_r0n(idx + 1, alloc_so_far, cap_left)
                return

            opts = sorted(set([0, min(rem, cap_left), min(rem, cap_left // 2)]))
            for use0 in opts:
                new_alloc = dict(alloc_so_far)
                if use0 > 0:
                    new_alloc[f"{h}_R0N"] = new_alloc.get(f"{h}_R0N", 0) + use0
                yield from recurse_r0n(idx + 1, new_alloc, cap_left - use0)

        for alloc_after_r0n in recurse_r0n(0, base_alloc, r0n_cap):
            # Split remaining units for each variable hole among allowed non-R0N/non-R0E regrinds.
            split_lists = []
            split_holes = []
            infeasible = False
            for h in variable_holes:
                demand = int(row[f"{h}_units"])
                assigned = sum(alloc_after_r0n.get(f"{h}_{r}", 0) for r in REGRIND_LEVELS)
                rem = max(0, demand - assigned)
                if rem == 0:
                    continue
                choices = [r for r in rules[h] if r not in ["R0E", "R0N"]]
                if not choices:
                    infeasible = True
                    break
                split_holes.append(h)
                split_lists.append(split_candidates(rem, choices))
            if infeasible:
                continue

            for split_product in itertools.product(*split_lists) if split_lists else [()]:
                alloc = dict(alloc_after_r0n)
                for h, split in zip(split_holes, split_product):
                    for r, v in split.items():
                        alloc[f"{h}_{r}"] = alloc.get(f"{h}_{r}", 0) + int(v)

                summary, _ = evaluate_pn_allocation(
                    row=row,
                    step=1,
                    alloc=alloc,
                    policy_name=policy_name,
                    order_name="candidate",
                    cost_weights=cost_weights,
                    w_change=step_policy["w_change"],
                    w_cost=step_policy["w_cost"],
                    w_due=0.0,
                    w_capacity=step_policy["w_capacity"],
                    w_quality=step_policy["w_quality"],
                    step_phase="candidate",
                    preferred_regrind=step_policy["prefer"],
                    rules=rules,
                    use_due_priority=False,
                    used_counts_before=used_counts_before,
                    inventory_allowed_counts=inventory_allowed_counts,
                    w_inventory_overuse_optimization=w_inventory_overuse_optimization,
                )

                if summary["objective_score"] < best_score:
                    best_score = summary["objective_score"]
                    best_alloc = alloc

    if best_alloc is None:
        return allocation_efficiency_first(row, rules)
    return best_alloc


