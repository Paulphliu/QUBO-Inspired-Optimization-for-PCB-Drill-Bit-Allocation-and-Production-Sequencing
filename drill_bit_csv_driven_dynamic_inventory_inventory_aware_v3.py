def load_production_plan(path: Path) -> pd.DataFrame:
    required = ["pn", "panels", "A_per_panel", "B_per_panel", "C_per_panel"]
    df = read_csv_with_validation(path, required, "production plan")

    if "batch_id" not in df.columns:
        df["batch_id"] = df["pn"].astype(str)
    if "due_priority" not in df.columns:
        df["due_priority"] = 0
    if "fixed_sequence" not in df.columns:
        df["fixed_sequence"] = np.nan
    if "remark" not in df.columns:
        df["remark"] = ""

    numeric_cols = ["panels", "A_per_panel", "B_per_panel", "C_per_panel", "due_priority"]
    for c in numeric_cols:
        df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0).astype(int)

    df["fixed_sequence"] = pd.to_numeric(df["fixed_sequence"], errors="coerce")

    if (df["panels"] <= 0).any():
        bad = df.loc[df["panels"] <= 0, ["pn", "batch_id", "panels"]]
        raise ValueError(f"Panels must be positive. Bad rows:\n{bad}")

    df["job_id"] = df["pn"].astype(str) + "|" + df["batch_id"].astype(str)
    return df


def load_inventory(path: Path) -> pd.DataFrame:
    """Load drill inventory and drill-life specification.

    V3 accepts the preferred format:
        regrind_level,available_count,min_reserve_count,capacity_hits,
        base_cost_weight,priority_consume,shortage_risk,inventory_mode,remark

    Recommended rows:
        R0E: stock row, first-life new drill, e.g. capacity_hits=250
        R0N: generated row, continuation life, e.g. capacity_hits=2750
        R1/R2/R3: stock rows with their own capacity_hits

    Backward compatibility:
        If an old R0 row is provided, it is expanded into R0E and R0N.
    """
    required = ["regrind_level", "available_count"]
    df = read_csv_with_validation(path, required, "drill inventory")
    df = df.copy()

    defaults = {
        "base_cost_weight": np.nan,
        "priority_consume": 0,
        "shortage_risk": 0,
        "min_reserve_count": 0,
        "capacity_hits": np.nan,
        "inventory_mode": "stock",
        "remark": "",
    }
    for col, default in defaults.items():
        if col not in df.columns:
            df[col] = default

    df["regrind_level"] = df["regrind_level"].astype(str).str.upper().str.strip()
    df["inventory_mode"] = df["inventory_mode"].fillna("stock").astype(str).str.lower().str.strip()

    # Backward compatibility for old R0 row.
    old_r0 = df[df["regrind_level"] == "R0"]
    extra_rows = []
    if len(old_r0) > 0:
        r0 = old_r0.iloc[0].to_dict()
        if not (df["regrind_level"] == "R0E").any():
            r0e = dict(r0)
            r0e["regrind_level"] = "R0E"
            r0e["capacity_hits"] = default_capacity_hits("R0E")
            r0e["inventory_mode"] = "stock"
            r0e["remark"] = "auto-expanded from old R0 row as R0E"
            extra_rows.append(r0e)
        if not (df["regrind_level"] == "R0N").any():
            r0n = dict(r0)
            r0n["regrind_level"] = "R0N"
            r0n["available_count"] = 0
            r0n["min_reserve_count"] = 0
            r0n["capacity_hits"] = default_capacity_hits("R0N")
            r0n["base_cost_weight"] = 0.0
            r0n["inventory_mode"] = "generated"
            r0n["remark"] = "auto-expanded from old R0 row as generated R0N"
            extra_rows.append(r0n)
    if extra_rows:
        df = pd.concat([df, pd.DataFrame(extra_rows)], ignore_index=True)

    # Keep only new explicit inventory levels.
    df = df[df["regrind_level"].isin(REGRIND_LEVELS)].copy()

    # Numeric conversions. Blank values are treated as 0 for stock counts and default for capacity/cost.
    for c in ["available_count", "priority_consume", "shortage_risk", "min_reserve_count"]:
        df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0).astype(int)
    df["base_cost_weight"] = pd.to_numeric(df["base_cost_weight"], errors="coerce")
    df["capacity_hits"] = pd.to_numeric(df["capacity_hits"], errors="coerce")

    rows = []
    for level in REGRIND_LEVELS:
        sub = df[df["regrind_level"] == level]
        if len(sub) == 0:
            # Auto-add missing row using safe defaults.
            count_level = inventory_level_to_count_level(level)
            rows.append({
                "regrind_level": level,
                "available_count": 0,
                "base_cost_weight": 0.0 if level == "R0N" else FALLBACK_BASE_COST_WEIGHTS.get(count_level, 1.0),
                "priority_consume": 0,
                "shortage_risk": 1 if level != "R0N" else 0,
                "min_reserve_count": 0,
                "capacity_hits": default_capacity_hits(level),
                "inventory_mode": "generated" if level == "R0N" else "stock",
                "remark": "auto-added missing row",
            })
        else:
            row = sub.iloc[0].to_dict()
            if pd.isna(row.get("capacity_hits", np.nan)) or int(row.get("capacity_hits", 0)) <= 0:
                row["capacity_hits"] = default_capacity_hits(level)
            count_level = inventory_level_to_count_level(level)
            if pd.isna(row.get("base_cost_weight", np.nan)):
                row["base_cost_weight"] = 0.0 if level == "R0N" else FALLBACK_BASE_COST_WEIGHTS.get(count_level, 1.0)
            if level == "R0N":
                row["inventory_mode"] = "generated"
                # R0N is generated by R0E usage; it is not independent warehouse stock.
                row["available_count"] = 0
                row["min_reserve_count"] = 0
            rows.append(row)

    out = pd.DataFrame(rows)
    out["capacity_hits"] = pd.to_numeric(out["capacity_hits"], errors="coerce").fillna(0).astype(int)
    for _, row in out.iterrows():
        hits = int(row["capacity_hits"])
        level = str(row["regrind_level"])
        if hits <= 0 or hits % UNIT_HITS != 0:
            raise ValueError(
                f"capacity_hits for {level} must be positive and divisible by UNIT_HITS={UNIT_HITS}. Got {hits}."
            )
    return out

def load_daily_policy(path: Path) -> pd.Series:
    required = ["policy_name", "active", "w_change", "w_cost"]
    df = read_csv_with_validation(path, required, "daily policy")

    defaults = {
        "w_due": 1.0,
        "w_inventory": 1.0,
        "w_capacity": 1.0,
        "w_quality": 1e9,
        "preferred_regrind": None,
        "preference_strength": 0.0,
        "remark": "",
    }
    for col, default in defaults.items():
        if col not in df.columns:
            df[col] = default

    active = df[pd.to_numeric(df["active"], errors="coerce").fillna(0).astype(int) == 1]
    if len(active) == 0:
        print("WARNING: No active daily policy found. Using the first policy row.")
        row = df.iloc[0].copy()
    elif len(active) > 1:
        print("WARNING: Multiple active daily policies found. Using the first active row.")
        row = active.iloc[0].copy()
    else:
        row = active.iloc[0].copy()

    for c in ["w_change", "w_cost", "w_due", "w_inventory", "w_capacity", "w_quality", "preference_strength"]:
        row[c] = float(pd.to_numeric(row[c], errors="coerce")) if not pd.isna(row[c]) else defaults.get(c, 0.0)

    pref = clean_str_value(row.get("preferred_regrind", None))
    row["preferred_regrind"] = pref.upper() if pref else None
    return row


def load_hole_regrind_rules(path: Path) -> Tuple[Dict[str, List[str]], pd.DataFrame]:
    """Load hole-type to allowed-regrind rules from CSV.

    Required columns:
        hole_type,regrind_level,allowed

    Example rows:
        A,R0E,1
        B,R0N,1
        B,R1,1
        B,R2,1
        C,R0E,1
        C,R0N,1
        C,R1,1
        C,R2,1
        C,R3,1
    """
    required = ["hole_type", "regrind_level", "allowed"]
    df = read_csv_with_validation(path, required, "hole regrind rule")
    df = df.copy()
    df["hole_type"] = df["hole_type"].astype(str).str.upper().str.strip()
    df["regrind_level"] = df["regrind_level"].astype(str).str.upper().str.strip()
    df["allowed"] = pd.to_numeric(df["allowed"], errors="coerce").fillna(0).astype(int)

    df = df[df["hole_type"].isin(HOLE_TYPES) & df["regrind_level"].isin(REGRIND_LEVELS)].copy()

    rules: Dict[str, List[str]] = {}
    for hole in HOLE_TYPES:
        allowed = df[(df["hole_type"] == hole) & (df["allowed"] == 1)]["regrind_level"].tolist()
        if not allowed:
            raise ValueError(f"hole_regrind_rule CSV has no allowed regrind level for hole type {hole}.")
        rules[hole] = allowed

    return rules, df


