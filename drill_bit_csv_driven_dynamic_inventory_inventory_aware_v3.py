# Public release version for reproducible academic testing.
"""
PCB drill-bit allocation with CSV-driven production, inventory, policy, and hole-rule settings
============================================================================================

This version reads four CSV files from the folder `drill_qubo_csv_templates`
placed next to this .py file:

1. production_plan_template.csv
2. drill_inventory_template_corrected.csv
3. daily_policy_template.csv
4. hole_regrind_rule_template.csv

The fourth CSV controls which regrind levels are allowed for each hole type.
Example:
    A: R0E
    B: R0N, R1, R2
    C: R0E, R0N, R1, R2, R3

Important modeling notes
------------------------
- R0E is treated as a new-drill first-life usage.
- Every physical R0E bit generates an R0N continuation capacity after first life.
- R0N allocations share that continuation capacity.
- R0E/R0N/R1/R2/R3 capacity_hits are read from drill_inventory_template_corrected.csv.
- R1/R2/R3 counts are computed from total assigned units divided by CSV-driven capacity units.
- Inventory available_count is now used in two ways:
  (1) common post-evaluation metrics for all policies;
  (2) an optimization-time overuse penalty for balanced_dynamic, so the proposed
      method actively avoids exceeding available_count - min_reserve_count.

Compared policies
-----------------
- efficiency_first
- static_cost_first
- dynamic_preference_greedy
- balanced_no_preference
- balanced_dynamic

Outputs are written to `drill_bit_csv_dynamic_output/`.
"""

