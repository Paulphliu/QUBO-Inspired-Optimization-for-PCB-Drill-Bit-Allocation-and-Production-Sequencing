def all_allocation_keys() -> List[str]:
    return [f"{h}_{r}" for h in HOLE_TYPES for r in REGRIND_LEVELS]


def normalize_alloc(alloc: Dict[str, int]) -> Dict[str, int]:
    return {k: max(0, int(alloc.get(k, 0))) for k in all_allocation_keys()}


def count_physical_bits(a: Dict[str, int]) -> Dict[str, int]:
    units_by_level = {r: 0 for r in REGRIND_LEVELS}
    for h in HOLE_TYPES:
        for r in REGRIND_LEVELS:
            units_by_level[r] += int(a.get(f"{h}_{r}", 0))

    r0e_units = units_by_level["R0E"]
    counts = {
        "R0": ceil_div(r0e_units, CAP_UNITS["R0E"]) if r0e_units > 0 else 0,
        "R1": ceil_div(units_by_level["R1"], CAP_UNITS["R1"]) if units_by_level["R1"] > 0 else 0,
        "R2": ceil_div(units_by_level["R2"], CAP_UNITS["R2"]) if units_by_level["R2"] > 0 else 0,
        "R3": ceil_div(units_by_level["R3"], CAP_UNITS["R3"]) if units_by_level["R3"] > 0 else 0,
    }
    return counts


def evaluate_pn_allocation(
    row: pd.Series,
    step: int,
    alloc: Dict[str, int],
    policy_name: str,
    order_name: str,
    cost_weights: Dict[str, float],
    w_change: float,
    w_cost: float,
    w_due: float,
    w_capacity: float,
    w_quality: float,
    step_phase: str,
    preferred_regrind: str | None,
    rules: Dict[str, List[str]],
    use_due_priority: bool = True,
    used_counts_before: Optional[Dict[str, int]] = None,
    inventory_allowed_counts: Optional[Dict[str, int]] = None,
    w_inventory_overuse_optimization: float = 0.0,
) -> Tuple[Dict, Dict]:
    a = normalize_alloc(alloc)
    demand_units = {h: int(row[f"{h}_units"]) for h in HOLE_TYPES}

    unmet_units = 0
    quality_violation_count = 0

    for h in HOLE_TYPES:
        assigned = 0
        for r in REGRIND_LEVELS:
            val = a.get(f"{h}_{r}", 0)
            assigned += val
            if val > 0 and r not in rules[h]:
                quality_violation_count += val
        unmet_units += abs(demand_units[h] - assigned)

    counts = count_physical_bits(a)
    tool_change_count = counts["R0"] + counts["R1"] + counts["R2"] + counts["R3"]

    r0n_used = sum(a.get(f"{h}_R0N", 0) for h in HOLE_TYPES)
    r0n_capacity = counts["R0"] * CAP_UNITS["R0N"]
    r0n_over = max(0, r0n_used - r0n_capacity)
    over_capacity_count = 1 if r0n_over > 0 else 0

    relative_cost_score = (
        cost_weights["R0"] * counts["R0"]
        + cost_weights["R1"] * counts["R1"]
        + cost_weights["R2"] * counts["R2"]
        + cost_weights["R3"] * counts["R3"]
    )

    raw_due_priority = int(row.get("due_priority", 0))
    due_priority = raw_due_priority if use_due_priority else 0
    due_penalty = due_priority * max(0, step - 1) * DUE_STEP_PENALTY_SCALE

    opt_overuse_count, opt_overuse_by_level = incremental_inventory_overuse(
        counts=counts,
        used_counts_before=used_counts_before,
        inventory_allowed_counts=inventory_allowed_counts,
    )
    optimization_inventory_overuse_penalty = (
        float(w_inventory_overuse_optimization) * float(opt_overuse_count)
    )

    objective_score = (
        w_change * tool_change_count
        + w_cost * relative_cost_score
        + w_due * due_penalty
        + optimization_inventory_overuse_penalty
        + w_quality * quality_violation_count
        + w_capacity * 1e9 * over_capacity_count
        + w_capacity * 1e9 * unmet_units
    )

    result = {
        "order_name": order_name,
        "policy_name": policy_name,
        "step": step,
        "job_id": row["job_id"],
        "pn": row["pn"],
        "batch_id": row["batch_id"],
        "due_priority": due_priority,
        "raw_due_priority": raw_due_priority,
        "fixed_sequence": row.get("fixed_sequence", np.nan),
        "step_phase": step_phase,
        "preferred_regrind": preferred_regrind if preferred_regrind is not None else "None",
        "w_change": w_change,
        "w_cost": w_cost,
        "w_due": w_due,
        "w_capacity": w_capacity,
        "cost_R0": cost_weights["R0"],
        "cost_R1": cost_weights["R1"],
        "cost_R2": cost_weights["R2"],
        "cost_R3": cost_weights["R3"],
        "R0_count": counts["R0"],
        "R1_count": counts["R1"],
        "R2_count": counts["R2"],
        "R3_count": counts["R3"],
        "tool_change_count": tool_change_count,
        "R0N_capacity_hits": r0n_capacity * UNIT_HITS,
        "R0N_used_hits": r0n_used * UNIT_HITS,
        "R0N_unused_hits": max(0, r0n_capacity - r0n_used) * UNIT_HITS,
        "relative_cost_score": relative_cost_score,
        "due_penalty": due_penalty,
        "objective_score": objective_score,
        "quality_violation_count": quality_violation_count,
        "over_capacity_count": over_capacity_count,
        "unmet_units": unmet_units,
        "optimization_inventory_overuse_count": int(opt_overuse_count),
        "optimization_inventory_overuse_penalty": float(optimization_inventory_overuse_penalty),
        "optimization_inventory_overuse_R0": int(opt_overuse_by_level["R0"]),
        "optimization_inventory_overuse_R1": int(opt_overuse_by_level["R1"]),
        "optimization_inventory_overuse_R2": int(opt_overuse_by_level["R2"]),
        "optimization_inventory_overuse_R3": int(opt_overuse_by_level["R3"]),
    }

    for h in HOLE_TYPES:
        result[f"{h}_hits"] = demand_units[h] * UNIT_HITS
        for r in REGRIND_LEVELS:
            result[f"{h}_{r}_hits"] = a.get(f"{h}_{r}", 0) * UNIT_HITS

    return result, a


