def add_improvement_columns(summary_df: pd.DataFrame, baseline_order: str = "original_order") -> pd.DataFrame:
    rows = []
    for policy_name, sub in summary_df.groupby("policy_name"):
        best_obj = sub["objective_score"].min()
        best_change = sub["tool_change_count"].min()
        best_cost = sub["relative_cost_score"].min()
        baseline = sub[sub["order_name"] == baseline_order]
        base = baseline.iloc[0] if len(baseline) else sub.iloc[0]
        base_obj = base["objective_score"]
        base_change = base["tool_change_count"]
        base_cost = base["relative_cost_score"]
        for _, row in sub.iterrows():
            row = row.to_dict()
            row["objective_reduction_vs_original_pct"] = (base_obj - row["objective_score"]) / base_obj * 100.0 if base_obj else 0.0
            row["change_reduction_vs_original_pct"] = (base_change - row["tool_change_count"]) / base_change * 100.0 if base_change else 0.0
            row["cost_reduction_vs_original_pct"] = (base_cost - row["relative_cost_score"]) / base_cost * 100.0 if base_cost else 0.0
            row["objective_gap_to_best_pct"] = (row["objective_score"] - best_obj) / best_obj * 100.0 if best_obj else 0.0
            row["change_gap_to_best_pct"] = (row["tool_change_count"] - best_change) / best_change * 100.0 if best_change else 0.0
            row["cost_gap_to_best_pct"] = (row["relative_cost_score"] - best_cost) / best_cost * 100.0 if best_cost else 0.0
            rows.append(row)
    return pd.DataFrame(rows)


def choose_policy_best_row(sub: pd.DataFrame, policy_name: str) -> pd.Series:
    if policy_name == "balanced_no_preference":
        rank_map = {"exhaustive_best": 0, "random_search_best": 1, "sa_sequence_best": 2, "high_A_first": 3, "high_C_first": 4, "high_C_last": 5, "original_order": 6}
    else:
        rank_map = {"exhaustive_best": 0, "random_search_best": 1, "sa_sequence_best": 2, "due_priority_first": 3, "fixed_sequence_candidate": 4, "original_order": 5, "high_A_first": 6, "high_C_first": 7, "high_C_last": 8}
    tmp = sub.copy()
    tmp["_best_row_rank"] = tmp["order_name"].map(rank_map).fillna(99)
    # objective_score already includes optimization_inventory_overuse_penalty
    # for balanced_dynamic. Add optimization overuse as an explicit tie-breaker
    # so the selected row is always the most inventory-feasible among equal scores.
    sort_cols = [
        "objective_score",
        "optimization_inventory_overuse_count" if "optimization_inventory_overuse_count" in tmp.columns else "_best_row_rank",
        "_best_row_rank",
        "tool_change_count",
        "relative_cost_score",
    ]
    # Remove duplicate columns while preserving order.
    sort_cols = list(dict.fromkeys(sort_cols))
    tmp = tmp.sort_values(sort_cols)
    return tmp.iloc[0].drop(labels=["_best_row_rank"])


def make_inventory_usage_summary(best_steps: pd.DataFrame, inventory_df: pd.DataFrame) -> pd.DataFrame:
    usage = {r: int(best_steps[f"{r}_count"].sum()) for r in COUNT_LEVELS}
    allowed_counts = build_inventory_allowed_counts(inventory_df)
    rows = []
    for r in COUNT_LEVELS:
        inv = inventory_row_for_count_level(inventory_df, r)
        available = int(inv.get("available_count", 0))
        reserve = int(inv.get("min_reserve_count", 0))
        used = usage[r]
        after = available - used
        allowed = int(allowed_counts.get(r, 0))
        rows.append({
            "count_level": r,
            "source_inventory_level": "R0E" if r == "R0" else r,
            "available_count": available,
            "allowed_count_after_reserve": allowed,
            "used_count_estimate": used,
            "remaining_count_estimate": after,
            "min_reserve_count": reserve,
            "below_reserve_after_run": int(after < reserve),
            "over_allowed_count": max(0, used - allowed),
        })
    return pd.DataFrame(rows)

