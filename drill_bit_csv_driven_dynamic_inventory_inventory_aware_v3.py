def exhaustive_sequence_search(pn_df, policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts=None):
    ignore_fixed = policy_name == "balanced_no_preference"
    free_jobs = get_free_jobs_for_search(pn_df, ignore_fixed=ignore_fixed)
    best_total = None
    best_steps = None
    count = 0
    for seq_tuple in itertools.permutations(free_jobs):
        count += 1
        seq = make_sequence_from_free_order(pn_df, list(seq_tuple), ignore_fixed=ignore_fixed)
        total, steps = simulate_sequence(pn_df, seq, f"perm_{count}", policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts)
        if best_total is None or total["objective_score"] < best_total["objective_score"]:
            best_total = total
            best_steps = steps
    best_total = dict(best_total)
    best_total["order_name"] = "exhaustive_best"
    best_steps = best_steps.copy()
    best_steps["order_name"] = "exhaustive_best"
    return best_total, best_steps


def random_sequence_search(pn_df, policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts=None, iterations=RANDOM_SEARCH_ITER, seed=RANDOM_SEED):
    rng = random.Random(seed)
    ignore_fixed = policy_name == "balanced_no_preference"
    free_jobs = get_free_jobs_for_search(pn_df, ignore_fixed=ignore_fixed)
    best_total = None
    best_steps = None
    for i in range(iterations):
        seq_free = free_jobs[:]
        rng.shuffle(seq_free)
        seq = make_sequence_from_free_order(pn_df, seq_free, ignore_fixed=ignore_fixed)
        total, steps = simulate_sequence(pn_df, seq, f"random_{i}", policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts)
        if best_total is None or total["objective_score"] < best_total["objective_score"]:
            best_total = total
            best_steps = steps
    best_total = dict(best_total)
    best_total["order_name"] = "random_search_best"
    best_steps = best_steps.copy()
    best_steps["order_name"] = "random_search_best"
    return best_total, best_steps


def sa_sequence_search(pn_df, policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts=None, seed=RANDOM_SEED):
    rng = random.Random(seed)
    ignore_fixed = policy_name == "balanced_no_preference"
    free_jobs = get_free_jobs_for_search(pn_df, ignore_fixed=ignore_fixed)
    if len(free_jobs) <= 1:
        seq = make_sequence_from_free_order(pn_df, free_jobs, ignore_fixed=ignore_fixed)
        return simulate_sequence(pn_df, seq, "sa_sequence_best", policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts)

    best_total = None
    best_steps = None
    for restart in range(SA_SEQUENCE_RESTARTS):
        cur_free = free_jobs[:]
        rng.shuffle(cur_free)
        cur_seq = make_sequence_from_free_order(pn_df, cur_free, ignore_fixed=ignore_fixed)
        cur_total, cur_steps = simulate_sequence(pn_df, cur_seq, f"sa_restart_{restart}", policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts)
        cur_score = cur_total["objective_score"]

        if best_total is None or cur_score < best_total["objective_score"]:
            best_total = cur_total
            best_steps = cur_steps

        for step in range(SA_SEQUENCE_STEPS):
            t = step / max(1, SA_SEQUENCE_STEPS - 1)
            temp = SA_T0 * ((SA_T_END / SA_T0) ** t)
            new_free = cur_free[:]
            i, j = rng.sample(range(len(new_free)), 2)
            new_free[i], new_free[j] = new_free[j], new_free[i]
            new_seq = make_sequence_from_free_order(pn_df, new_free, ignore_fixed=ignore_fixed)
            new_total, new_steps = simulate_sequence(pn_df, new_seq, "sa_tmp", policy_name, active_policy, cost_weights, base_cost_weights, rules, inventory_allowed_counts)
            new_score = new_total["objective_score"]
            if new_score <= cur_score:
                accept = True
            else:
                prob = math.exp(-(new_score - cur_score) / max(temp, 1e-12))
                accept = rng.random() < prob
            if accept:
                cur_free = new_free
                cur_total = new_total
                cur_steps = new_steps
                cur_score = new_score
            if cur_score < best_total["objective_score"]:
                best_total = cur_total
                best_steps = cur_steps

    best_total = dict(best_total)
    best_total["order_name"] = "sa_sequence_best"
    best_steps = best_steps.copy()
    best_steps["order_name"] = "sa_sequence_best"
    return best_total, best_steps


